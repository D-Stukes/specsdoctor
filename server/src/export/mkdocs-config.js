// §4d "Export ZIP contents": mkdocs.yml sets theme: material and the
// pymdownx.superfences custom fence for Mermaid, plus admonition so inline
// warnings render.
export function buildMkdocsYml(repo) {
  return `site_name: ${repo.owner}/${repo.name} docs
theme:
  name: material
markdown_extensions:
  - admonition
  - pymdownx.superfences:
      custom_fences:
        - name: mermaid
          class: mermaid
          format: !!python/name:pymdownx.superfences.fence_code_format
`;
}

export function buildExportReadme() {
  return `# Exported docs

Generated by DocSync - a source-linked documentation draft, not a verified spec. Every technical claim cites the exact lines it came from; anything uncertain is flagged for human review (see \`review.md\` if you included it).

## View locally

\`\`\`bash
pip install mkdocs-material
mkdocs serve
\`\`\`

Then open the printed localhost URL. \`mkdocs build --strict\` also works, if you want a static build.
`;
}
